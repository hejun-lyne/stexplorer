const NON_THEME_RE: RegExp[] = NON_THEME_PATTERNS.map((p) => new RegExp(p));
const INDUSTRY_THEME_RE: RegExp = new RegExp(INDUSTRY_THEME_KEYWORDS.join('|'));

/** true = 题材属性板块；false = 风格/指数/持仓/地域等伪概念 */
export function isThemeBoard(name: string): boolean {
  const text = String(name || '').trim();
  if (!text) {
    return false;
  }
  // 明确伪概念优先：避免「参股银行」「次新股概念」被行业关键词救回来
  if (NON_THEME_RE.some((rx) => rx.test(text))) {
    return false;
  }
  // 行业/产业/技术题材保留
  return INDUSTRY_THEME_RE.test(text);
}

/** 过滤出题材板块（保留原始对象） */
export function filterThemeBoards<T extends { name?: string }>(boards: T[]): T[] {
  return (boards || []).filter((b) => isThemeBoard(String(b?.name || '')));
}
